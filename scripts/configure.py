"""Render disposable Docker files from configs/inferops.yaml and .env.

No inference dependencies are needed. The Docker-only launcher runs this inside
its small configuration image. Generated files are private and never editable.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import tempfile
from pathlib import Path
from urllib.parse import quote

import yaml
from dotenv import dotenv_values

APP = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(APP))

from inferops.adapters.outbound.projects import central  # noqa: E402


def write_private(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode="w", dir=path.parent, delete=False, encoding="utf-8") as stream:
        stream.write(content)
        temporary = Path(stream.name)
    try:
        temporary.chmod(0o600)
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


def env_text(values):
    # Compose dotenv single quoting keeps $, backticks and command text literal.
    return "# GENERATED by scripts/configure.py; edit configs/inferops.yaml or .env.\n" + "".join(
        key + "='" + str(value).replace("\\", "\\\\").replace("'", "\\'") + "'\n"
        for key, value in sorted(values.items()) if value is not None
    )


def render(*, config_file=None, output=None, mode=None, port=None, profiles=None, environ=None):
    path = Path(config_file or APP / "configs/inferops.yaml").resolve()
    data = central.read_config(path)
    # Host overrides and secrets win, but generated values from a parent process
    # are defaults, not new user overrides.
    process = dict(os.environ if environ is None else environ)
    inherited = json.loads(process.get("INFEROPS_CONFIG_VALUES", "{}"))
    explicit = {key: value for key, value in process.items()
                if (key.startswith("INFEROPS_") or key in {"HF_TOKEN", "COMPOSE_PROFILES"})
                and inherited.get(key) != value}
    secrets = {key: value for key, value in dotenv_values(path.parent.parent / ".env").items() if value is not None}
    values = {**central.environment(path, data, context="docker"), **secrets, **explicit}
    if mode is not None:
        values["INFEROPS_EXECUTION_MODE"] = mode
    if port is not None:
        values["INFEROPS_API_PORT"] = str(port)
    selected_mode = values["INFEROPS_EXECUTION_MODE"]
    if selected_mode not in {"auto", "cpu", "cuda", "triton"}:
        raise ValueError("Docker mode must be cpu, cuda or triton (auto is CPU)")
    if not 1 <= int(values["INFEROPS_API_PORT"]) <= 65535:
        raise ValueError("API port must be between 1 and 65535")
    if profiles is not None:
        data["runtime"]["services"] = profiles
    services = data.get("runtime", {}).get("services", [])
    values["INFEROPS_MONITORING_ENABLED"] = str("monitoring" in services).lower()
    values["COMPOSE_PROFILES"] = ",".join(dict.fromkeys([selected_mode, *services]))
    if values.get("INFEROPS_STORAGE_KIND") == "s3" and "storage" not in services and not values.get("INFEROPS_S3_ENDPOINT"):
        raise ValueError("storage.kind: s3 needs runtime.services: [storage] or an external S3 endpoint")
    selected_root = values.get("INFEROPS_PROJECT_ROOT")
    if not selected_root:
        raise ValueError("Select runtime.project in configs/inferops.yaml (or set INFEROPS_PROJECT_ROOT in .env)")
    root = Path(selected_root)
    if not root.is_absolute():
        root = path.parent.parent / root
    values["INFEROPS_PROJECT_ROOT"] = str(root.resolve())
    values["INFEROPS_CONFIG_PROJECT"] = central.project_key(path, data, root.resolve()) or ""
    values.setdefault("INFEROPS_TRITON_REPOSITORY", str(root.resolve() / "model_repository"))
    values["INFEROPS_CONFIG_DIRECTORY"] = str(path.parent)
    # Preserve host absolute video paths inside API and camera workers.
    media_root = Path(values.get("INFEROPS_MEDIA_ROOT", str(APP / "research"))).expanduser()
    if not media_root.is_absolute():
        media_root = path.parent.parent / media_root
    values["INFEROPS_MEDIA_ROOT"] = str(media_root.resolve())
    values.setdefault("INFEROPS_IMAGE", "inferops-engine:local")
    values.setdefault("INFEROPS_KAFKA_HOST", data.get("docker", {}).get("kafka_host", "localhost"))
    values.setdefault("INFEROPS_PROMETHEUS_CONFIG", str(APP / "deploy/observability/prometheus.yml"))
    # Credentials are only sourced from .env / the host. Defaults keep an existing
    # developer .env compatible with the bundled local services.
    user = values.setdefault("INFEROPS_PG_USER", "postgres")
    password = values.setdefault("INFEROPS_PG_PASSWORD", "postgres")
    database = values.setdefault("INFEROPS_PG_DATABASE", "inferops")
    authority = f"{quote(user, safe='')}:{quote(password, safe='')}"
    container = dict(values)
    internal = {
        "INFEROPS_DATABASE_URL": f"postgresql+asyncpg://{authority}@postgres:5432/{quote(database, safe='')}",
        "INFEROPS_S3_ENDPOINT": "http://minio:9000", "INFEROPS_S3_PUBLIC_URL": "http://localhost:" + values.get("INFEROPS_S3_PORT", "9000"),
        "INFEROPS_TRANSPORT_BOOTSTRAP": "redpanda:9092",
        "INFEROPS_TRITON_URL": "triton:8001", "INFEROPS_TRITON_HTTP_URL": "http://triton:8000",
        "INFEROPS_TRITON_METRICS_URL": "http://triton:8002",
        "INFEROPS_MEDIAMTX_API_URL": "http://mediamtx:9997", "INFEROPS_MEDIAMTX_RTSP_URL": "rtsp://mediamtx:8554",
        "INFEROPS_MEDIAMTX_PLAYBACK_URL": "http://mediamtx:9996",
        "INFEROPS_MINIO_CONSOLE_INTERNAL_URL": "http://minio:9001", "INFEROPS_GRAFANA_INTERNAL_URL": "http://grafana:3000",
        "INFEROPS_PROMETHEUS_INTERNAL_URL": "http://prometheus:9090",
    }
    for key, value in internal.items():
        container.setdefault(key, value)
    if "INFEROPS_DATABASE_URL" not in values and values.get("INFEROPS_PG_URL"):
        container["INFEROPS_DATABASE_URL"] = values["INFEROPS_PG_URL"]
    container.update(INFEROPS_CONFIG_CONTEXT="docker", INFEROPS_CONFIG_FILE="/app/configs/inferops.yaml",
                     INFEROPS_CONFIGS_DIR="/app/configs", INFEROPS_DOMAIN_ROOT="/project",
                     INFEROPS_PROJECT_ROOT="/project", INFEROPS_API_PORT="8080",
                     INFEROPS_DATA_PATH="/var/lib/inferops/data", INFEROPS_SOURCES_PATH="/var/lib/inferops/sources",
                     INFEROPS_SPOOL_PATH="/var/lib/inferops/spool", INFEROPS_CAPACITY_REPORTS="/var/lib/inferops/capacity")
    owned = central.environment(path, data, context="docker")
    # Container-local paths and the internal API port cannot follow host paths/ports.
    fixed = {"INFEROPS_PROJECT_ROOT", "INFEROPS_API_PORT", "INFEROPS_DATA_PATH", "INFEROPS_SPOOL_PATH"}
    owned = {key: value for key, value in owned.items() if key not in fixed and container.get(key) == value
             and key not in secrets and key not in explicit}
    container["INFEROPS_CONFIG_VALUES"] = json.dumps(owned, separators=(",", ":"))
    output = Path(output or path.parent.parent / ".run").resolve()
    values["INFEROPS_CONTAINER_ENV"] = str(output / "container.env")
    paths = [str(APP / "deploy/compose.yaml"), str(APP / f"deploy/compose/{selected_mode}.yaml")]
    if data.get("workers"):
        ids = {worker["worker_id"] for worker in data["workers"].get("workers", [])}
        if selected_mode != "triton" or values.get("INFEROPS_STORAGE_KIND") != "s3" or ids != {"a", "b"}:
            raise ValueError("The bundled static worker layout requires Triton, shared S3 and worker IDs a/b")
        if not values.get("INFEROPS_WORKER_TOKEN"):
            raise ValueError("Static workers require INFEROPS_WORKER_TOKEN in .env")
        paths.append(str(APP / "deploy/compose/workers.yaml"))
    wrapper = {"include": [{"path": paths,
                            "project_directory": str(APP), "env_file": str(output / "compose.env")} ]}
    write_private(output / "container.env", env_text(container))
    write_private(output / "compose.env", env_text(values))
    write_private(output / "compose.yaml", "# GENERATED; edit configs/inferops.yaml.\n" + yaml.safe_dump(wrapper, sort_keys=False))
    return values


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config")
    parser.add_argument("--output")
    parser.add_argument("--mode", choices=["cpu", "auto", "cuda", "triton"])
    parser.add_argument("--port", type=int)
    args = parser.parse_args()
    render(config_file=args.config, output=args.output, mode=args.mode, port=args.port)
    print("Configuration ready: configs/inferops.yaml + .env")


if __name__ == "__main__":
    main()
