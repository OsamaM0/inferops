"""End-to-end browser scenario for the InferOps dashboard.

Drives a real Chromium session through a driver-behaviour incident and captures
a numbered screenshot at every step, so the run is reviewable after the fact.

It is a *test*, not a demo: every step asserts, and the script exits non-zero on
the first failure.

Prerequisites
-------------
    make serve-mock DOMAIN=driver_behaviour
    pip install playwright && python -m playwright install chromium

Usage
-----
    python scripts/e2e_dashboard_scenario.py
    python scripts/e2e_dashboard_scenario.py --out /tmp/shots

Pass ``--docs`` to additionally write the stable-named images embedded in the
README, so the documentation screenshots are regenerated by the same run that
verifies the behaviour they illustrate and cannot drift from it.

Note on detections
------------------
With no GPU, no Triton and no downloaded weights, the `detect` stage falls back
to `rfdetr_driver_synth`. That backend emits a deterministic, time-varying
detection pattern, so the *pipeline* is exercised for real end to end while the
detections themselves do not depend on frame pixels. The generated frames make
the screenshots legible; they are not what the synthetic detector reacts to.
"""
from __future__ import annotations

import argparse
import asyncio
import json
import sys
import urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
GIT_ROOT = REPO_ROOT.parent

API = "http://127.0.0.1:8080"
DASHBOARD = "http://127.0.0.1:8090/dashboard.html"

console_errors: list[str] = []
page_errors: list[str] = []
failed_requests: list[str] = []
bad_responses: list[str] = []


# ── frame generation ─────────────────────────────────────────────────────────

def _make_frames(out_dir: Path) -> dict[str, Path]:
    """Render two legible driver frames: attentive, then phone-in-hand."""
    import cv2
    import numpy as np

    def base(label: str) -> np.ndarray:
        img = np.full((480, 640, 3), 32, np.uint8)
        cv2.rectangle(img, (0, 360), (640, 480), (48, 48, 56), -1)      # dashboard
        cv2.ellipse(img, (320, 470), (150, 70), 0, 180, 360, (90, 90, 100), 8)  # wheel
        cv2.rectangle(img, (215, 150), (425, 380), (96, 122, 158), -1)  # torso
        cv2.circle(img, (320, 175), 78, (168, 190, 214), -1)            # head
        cv2.circle(img, (295, 165), 8, (30, 30, 30), -1)                # eyes
        cv2.circle(img, (345, 165), 8, (30, 30, 30), -1)
        cv2.ellipse(img, (320, 205), (26, 12), 0, 0, 180, (60, 40, 40), 3)  # mouth
        cv2.putText(img, label, (18, 34), cv2.FONT_HERSHEY_SIMPLEX, 0.7,
                    (235, 235, 235), 2)
        return img

    frames = {}
    attentive = base("SCENARIO 1/2  attentive driver")
    frames["attentive"] = out_dir / "frame_attentive.jpg"
    cv2.imwrite(str(frames["attentive"]), attentive)

    phone = base("SCENARIO 2/2  phone in hand")
    cv2.rectangle(phone, (388, 150), (436, 240), (18, 18, 18), -1)      # phone body
    cv2.rectangle(phone, (392, 156), (432, 232), (70, 130, 180), -1)    # phone screen
    cv2.circle(phone, (400, 265), 30, (150, 172, 196), -1)              # hand
    frames["phone"] = out_dir / "frame_phone.jpg"
    cv2.imwrite(str(frames["phone"]), phone)
    return frames


# ── helpers ──────────────────────────────────────────────────────────────────

def _api_json(path: str):
    with urllib.request.urlopen(f"{API}{path}", timeout=10) as r:
        return json.loads(r.read())


# The dashboard uses three different card elements depending on the region.
_PANEL_ELEMENTS = "article.summary-card, article.panel, aside.panel"


def _panel_with(inner_selector: str) -> str:
    """CSS for the card that contains ``inner_selector``.

    Uses :has() so documentation images include each panel's own heading and
    description rather than a context-free list of rows, and :is() because the
    summary row, the workspace panels and the preview aside are different
    elements.
    """
    return f":is({_PANEL_ELEMENTS}):has({inner_selector})"


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise AssertionError(message)


class Steps:
    def __init__(self, out_dir: Path, docs_dir: Path | None = None) -> None:
        self.out = out_dir
        self.docs_dir = docs_dir
        self.n = 0
        self.docs_written: list[Path] = []

    async def doc_shot(self, page, selector: str | None, name: str) -> None:
        """Write a stable-named image used by the README.

        ``selector`` of None captures the viewport. These are deliberately
        viewport- or element-scoped: a full_page capture of this dashboard is
        ~8000px tall and unreadable at documentation width.
        """
        if self.docs_dir is None:
            return
        path = self.docs_dir / f"{name}.png"
        if selector is None:
            await page.screenshot(path=str(path))
        else:
            element = page.locator(selector).first
            await element.scroll_into_view_if_needed()
            await page.wait_for_timeout(250)
            await element.screenshot(path=str(path))
        self.docs_written.append(path)
        print(f"    docs image -> {path.name}")

    async def shot(self, page, name: str, *, full: bool = False) -> Path:
        self.n += 1
        path = self.out / f"{self.n:02d}-{name}.png"
        await page.screenshot(path=str(path), full_page=full)
        print(f"    screenshot -> {path.name}")
        return path

    async def shot_element(self, page, selector: str, name: str) -> Path:
        """Screenshot one panel.

        A full_page shot of this dashboard is ~8000px tall because the raw-JSON
        result panel expands, which makes the interesting panels illegible.
        """
        self.n += 1
        path = self.out / f"{self.n:02d}-{name}.png"
        element = page.locator(selector).first
        await element.scroll_into_view_if_needed()
        await page.wait_for_timeout(250)
        await element.screenshot(path=str(path))
        print(f"    screenshot -> {path.name}")
        return path


# ── scenario ─────────────────────────────────────────────────────────────────

async def run(out_dir: Path, docs_dir: Path | None = None) -> int:
    from playwright.async_api import async_playwright

    frames = _make_frames(out_dir)
    steps = Steps(out_dir, docs_dir)

    async with async_playwright() as p:
        browser = await p.chromium.launch()
        ctx = await browser.new_context(viewport={"width": 1600, "height": 1150})
        await ctx.add_init_script(
            f"localStorage.setItem('inferops.dashboard.apiBase', '{API}');"
        )
        page = await ctx.new_page()
        page.on("console", lambda m: console_errors.append(f"[{m.type}] {m.text}")
                if m.type in ("error", "warning") else None)
        page.on("pageerror", lambda e: page_errors.append(str(e)))
        page.on("requestfailed", lambda r: failed_requests.append(f"{r.url} -> {r.failure}"))
        page.on("response", lambda r: bad_responses.append(f"{r.status} {r.url}")
                if r.status >= 400 else None)

        # ── Step 1: the dashboard connects to a live API ─────────────────────
        print("\n[1] Dashboard loads and connects")
        await page.goto(DASHBOARD, wait_until="networkidle", timeout=60_000)
        await page.wait_for_timeout(2_000)
        badge = (await page.inner_text("#apiConnectionBadge")).strip()
        models = (await page.inner_text("#summaryModels")).strip()
        print(f"    connection badge : {badge}")
        print(f"    models loaded    : {models}")
        _require("CONNECT" in badge.upper(), f"dashboard did not connect: {badge!r}")
        _require(models not in ("", "-", "0"), "no models registered")
        await steps.shot(page, "connected")
        await steps.doc_shot(page, None, "01-dashboard-overview")

        # ── Step 2: runtime / device panel ───────────────────────────────────
        print("\n[2] Runtime device reporting")
        runtime = _api_json("/v1/system/status")["runtime"]
        print(f"    onnxruntime      : {runtime['onnxruntime_version']}")
        print(f"    providers        : {', '.join(runtime['available_providers'])}")
        print(f"    cuda_available   : {runtime['cuda_available']}")
        print(f"    downgraded models: {runtime['models_downgraded'] or 'none'}")
        _require("cuda_available" in runtime, "runtime block missing cuda_available")
        await steps.shot_element(page, "#runtimeList", "runtime-snapshot")
        await steps.shot_element(page, "#serviceGrid", "core-services")
        await steps.doc_shot(page, _panel_with("#serviceGrid"), "02-core-services")

        # ── Step 3: attentive driver ─────────────────────────────────────────
        print("\n[3] Image mode — attentive driver")
        await page.click('.mode-tab[data-mode="image"]')
        await page.fill("#imageStreamIdInput", "scenario-cam")
        await page.set_input_files("#imageFileInput", str(frames["attentive"]))
        await page.click("#imageRunBtn")
        await page.wait_for_timeout(1_500)
        print(f"    frames processed : {(await page.inner_text('#resultFrames')).strip()}")
        _require((await page.inner_text("#resultFrames")).strip() == "1",
                 "pipeline did not report a processed frame")
        await steps.shot(page, "attentive-run")

        # ── Step 4: phone in hand, until fusion escalates ────────────────────
        print("\n[4] Image mode — phone in hand, driving fusion to an alert")
        await page.set_input_files("#imageFileInput", str(frames["phone"]))
        fired = False
        for i in range(1, 13):
            await page.click("#imageRunBtn")
            await page.wait_for_timeout(1_100)
            alerts = (await page.inner_text("#resultAlerts")).strip()
            events = (await page.inner_text("#resultEvents")).strip()
            dets = (await page.inner_text("#resultDetections")).strip()
            print(f"    run {i:>2}: detections={dets} events={events} alerts={alerts}")
            if alerts not in ("", "-", "0"):
                fired = True
                break
        _require(fired, "fusion never escalated to an alert")
        alert_text = (await page.inner_text("#resultAlertList")).replace("\n", " | ")
        print(f"    ALERT            : {alert_text[:160]}")
        await steps.shot(page, "alert-fired")
        await steps.shot_element(page, "#previewOverlay", "detection-overlay")
        await steps.shot_element(page, "#resultAlertList", "alert-detail")
        await steps.doc_shot(page, "#previewOverlay", "04-live-detection")
        await steps.doc_shot(page, _panel_with("#modeTabs"), "05-execution-studio")

        # ── Step 5: the real dashcam clip through the REST pipeline ──────────
        print("\n[5] Real dashcam video through POST /v1/run/{pipeline}/upload")
        video = GIT_ROOT / "train" / "test.mp4"
        if video.is_file():
            import subprocess
            proc = subprocess.run(
                ["curl", "-sS", "-X", "POST",
                 f"{API}/v1/run/driver_behaviour/upload",
                 # the form field is `video`, per POST /v1/run/{pipeline}/upload
                 "-F", f"video=@{video}", "-F", "stream_id=scenario-video"],
                capture_output=True, text=True, timeout=600,
            )
            body = json.loads(proc.stdout) if proc.stdout.strip().startswith("{") else {}
            _require(bool(body), f"video upload returned no JSON: {proc.stdout[:300]}")
            frames = body.get("frames", 0)
            events = body.get("fusion_events", [])
            alerts = body.get("alerts", [])
            print(f"    clip             : {video.name}")
            print(f"    shape            : {body.get('pipeline_shape', '?')}")
            print(f"    frames decoded   : {frames}")
            print(f"    detections       : {body.get('detections_by_class', {})}")
            print(f"    events / alerts  : {len(events)} / {len(alerts)}")
            _require(frames > 0, f"no frames decoded from {video.name}")
            _require(body.get("detections_by_class"), "video run produced no detections")
        else:
            print(f"    SKIPPED (no clip at {video})")

        # ── Step 6: persisted activity ───────────────────────────────────────
        print("\n[6] Persisted activity (alerts + events survive the request)")
        await page.click("#activityRefreshBtn")
        await page.wait_for_timeout(2_000)
        alerts_panel = (await page.inner_text("#alertsList")).replace("\n", " | ")
        events_panel = (await page.inner_text("#eventsList")).replace("\n", " | ")
        print(f"    alerts panel     : {alerts_panel[:150]}")
        print(f"    events panel     : {events_panel[:150]}")
        _require("No recent alerts" not in alerts_panel, "alerts were not persisted")
        _require("No recent events" not in events_panel, "events were not persisted")
        await steps.shot_element(page, "#alertsList", "persisted-alerts")
        await steps.shot_element(page, "#eventsList", "persisted-events")
        await steps.doc_shot(page, _panel_with("#alertsList"), "06-activity-persistence")
        # Captured here, not at step 2: the counters are only meaningful once
        # the scenario has actually pushed work through the pipeline.
        await page.click("#refreshBtn")
        await page.wait_for_timeout(1_200)
        await steps.doc_shot(page, _panel_with("#runtimeList"), "03-runtime-snapshot")

        # ── Step 7: config editor + live reload ──────────────────────────────
        print("\n[7] Config editor and live reload")
        await page.click("#configReloadAllBtn")
        await page.wait_for_timeout(1_800)
        print(f"    reload status    : {(await page.inner_text('#configStatus')).strip()[:120]}")
        await steps.shot_element(page, "#configList", "config-files")
        await steps.doc_shot(page, _panel_with("#configList"), "07-config-editor")

        await browser.close()

    # ── Step 8: browser health ───────────────────────────────────────────────
    print("\n[8] Browser health over the whole scenario")
    print(f"    console errors   : {len(console_errors)}")
    print(f"    page errors      : {len(page_errors)}")
    print(f"    failed requests  : {len(failed_requests)}")
    print(f"    non-2xx responses: {len(bad_responses)}")
    for bucket, items in (("console", console_errors), ("page", page_errors),
                          ("request", failed_requests), ("http", bad_responses)):
        for item in items[:10]:
            print(f"      {bucket}: {item[:200]}")
    _require(not page_errors, f"uncaught JS errors: {page_errors[:3]}")
    _require(not failed_requests, f"failed requests: {failed_requests[:3]}")
    _require(not bad_responses, f"non-2xx responses: {bad_responses[:3]}")
    _require(not console_errors, f"console errors/warnings: {console_errors[:3]}")

    print(f"\nSCENARIO PASSED — {steps.n} screenshots in {out_dir}")
    if steps.docs_written:
        print(f"Documentation images refreshed ({len(steps.docs_written)}):")
        for path in steps.docs_written:
            print(f"  {path}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", default=str(REPO_ROOT / ".run" / "scenario"),
                        help="screenshot output directory")
    parser.add_argument("--docs", action="store_true",
                        help="also refresh the stable-named images embedded in the README")
    parser.add_argument("--docs-out", default=str(GIT_ROOT / "docs" / "images"),
                        help="destination for --docs images")
    args = parser.parse_args()
    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)
    docs_dir = None
    if args.docs:
        docs_dir = Path(args.docs_out)
        docs_dir.mkdir(parents=True, exist_ok=True)

    try:
        return asyncio.run(run(out_dir, docs_dir))
    except AssertionError as exc:
        print(f"\nSCENARIO FAILED: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
