"""Source catalog and result-history persistence boundary."""

from __future__ import annotations

from typing import Protocol

from inferops.domain.sources import SourceSpec


class SourceRelay(Protocol):
    """Optional compressed-stream routing; decoding remains in the source reader."""

    async def prepare(self, spec: SourceSpec) -> SourceSpec: ...
    def path(self, camera_id: str) -> str: ...
    async def remove(self, camera_id: str) -> None: ...
    async def close(self) -> None: ...


class SourceStore(Protocol):
    async def start(self) -> None: ...
    async def close(self) -> None: ...
    async def list_sources(self) -> list[SourceSpec]: ...
    async def put_source(self, spec: SourceSpec) -> None: ...
    async def delete_source(self, camera_id: str) -> None: ...
    async def save_run(self, row: dict) -> None: ...
    async def list_runs(self, camera_id: str, limit: int = 50) -> list[dict]: ...
    async def save_result(self, camera_id: str, session_id: str, row: dict) -> None: ...
    async def list_results(self, camera_id: str, limit: int = 50) -> list[dict]: ...
    async def save_preview(self, camera_id: str, jpeg: bytes) -> None: ...
    async def get_preview(self, camera_id: str) -> bytes | None: ...
